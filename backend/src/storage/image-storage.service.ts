import {
  BadRequestException,
  Injectable,
  Logger,
  OnModuleInit,
  PayloadTooLargeException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'node:crypto';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import { basename, isAbsolute, join, relative, resolve } from 'node:path';
import { fileTypeFromBuffer } from 'file-type';

/** 2 MB default, shared by the product image interceptor and the service. */
export const MAX_IMAGE_SIZE_BYTES = 2 * 1024 * 1024;

/** Avatars are smaller; enforced by the interceptor and the service. */
export const MAX_AVATAR_SIZE_BYTES = 1 * 1024 * 1024;

/** Public URL prefix served by the static-assets middleware (`main.ts`). */
export const IMAGE_URL_PREFIX = '/uploads/';

/** Extensions produced by `file-type` for the formats we accept. */
const ALLOWED_EXTENSIONS = new Set(['jpg', 'png', 'webp']);

/** One safe path segment, e.g. `products` or `avatars`. */
const FOLDER_PATTERN = /^[a-z0-9][a-z0-9_-]*$/;

/** Names generated by `save`; only those files are ever deleted. */
const GENERATED_FILENAME_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$/i;

/**
 * Resolves `UPLOADS_DIR` to an absolute directory. Relative values are
 * relative to the process working directory (the Docker workdir in prod).
 */
export function resolveUploadsDir(configured?: string): string {
  const value = configured?.trim() || 'uploads';
  return isAbsolute(value) ? value : resolve(process.cwd(), value);
}

/**
 * The subset of multer's file object we need. Defining it locally keeps the
 * service trivial to unit test and avoids depending on Express.Multer globals.
 */
export interface UploadedImageFile {
  buffer: Buffer;
  size: number;
  mimetype?: string;
  originalname?: string;
}

/**
 * Shared disk storage for uploaded images (product images, avatars, ...).
 *
 * - Files live in `<UPLOADS_DIR>/<folder>/`.
 * - Names are generated UUIDs; client filenames are never used.
 * - The extension comes from the detected magic bytes, not the mimetype or
 *   the client-provided filename.
 * - Only relative `/uploads/...` URLs generated here are owned by the service;
 *   external URLs are never deleted.
 */
@Injectable()
export class ImageStorageService implements OnModuleInit {
  private readonly logger = new Logger(ImageStorageService.name);
  readonly uploadsDir: string;

  constructor(config: ConfigService) {
    this.uploadsDir = resolveUploadsDir(config.get<string>('UPLOADS_DIR'));
  }

  async onModuleInit(): Promise<void> {
    await mkdir(this.uploadsDir, { recursive: true });
  }

  /**
   * Validates and writes one image into `folder`. Returns the relative URL to
   * persist in the database. The caller owns cleanup if the subsequent DB
   * write fails.
   */
  async save(
    file: UploadedImageFile | undefined,
    folder: string,
    maxBytes = MAX_IMAGE_SIZE_BYTES,
  ): Promise<string> {
    if (!FOLDER_PATTERN.test(folder)) {
      throw new BadRequestException('Invalid upload folder');
    }

    if (!file || !file.buffer || file.buffer.length === 0) {
      throw new BadRequestException('An image file is required');
    }

    if (file.size > maxBytes || file.buffer.length > maxBytes) {
      throw new PayloadTooLargeException(
        `Image must be ${maxBytes / (1024 * 1024)} MB or smaller`,
      );
    }

    const detected = await fileTypeFromBuffer(file.buffer);
    if (!detected || !ALLOWED_EXTENSIONS.has(detected.ext)) {
      throw new BadRequestException(
        'Unsupported image type. Allowed types: JPEG, PNG, WebP',
      );
    }

    const directory = join(this.uploadsDir, folder);
    await mkdir(directory, { recursive: true });

    const filename = `${randomUUID()}.${detected.ext}`;
    await writeFile(join(directory, filename), file.buffer, { flag: 'wx' });

    return `${IMAGE_URL_PREFIX}${folder}/${filename}`;
  }

  /**
   * Deletes a local image if (and only if) it is a generated
   * `/uploads/<folder>/<uuid>.<ext>` path. Missing files are ignored, and
   * external URLs are left untouched.
   */
  async delete(imageUrl: string | null | undefined): Promise<void> {
    const absolutePath = this.resolveLocalPath(imageUrl);
    if (!absolutePath) {
      return;
    }

    try {
      await unlink(absolutePath);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
        return;
      }
      this.logger.warn(
        `Could not delete image ${absolutePath}: ${
          error instanceof Error ? error.message : String(error)
        }`,
      );
    }
  }

  /**
   * Maps a stored URL to a path inside `uploadsDir`, or null when the URL is
   * external, not a generated name, or would escape the uploads directory.
   */
  resolveLocalPath(imageUrl: string | null | undefined): string | null {
    if (!imageUrl || !imageUrl.startsWith(IMAGE_URL_PREFIX)) {
      return null;
    }

    const rest = imageUrl.slice(IMAGE_URL_PREFIX.length);
    if (!rest || rest.includes('..') || rest.includes('\\')) {
      return null;
    }

    const segments = rest.split('/');
    if (segments.length !== 2) {
      return null;
    }

    const [folder, filename] = segments;
    if (
      !FOLDER_PATTERN.test(folder) ||
      !GENERATED_FILENAME_PATTERN.test(filename) ||
      filename !== basename(filename)
    ) {
      return null;
    }

    const uploadsRoot = resolve(this.uploadsDir);
    const absolutePath = resolve(uploadsRoot, folder, filename);
    const relativePath = relative(uploadsRoot, absolutePath);
    if (
      !relativePath ||
      relativePath.startsWith('..') ||
      isAbsolute(relativePath)
    ) {
      return null;
    }

    return absolutePath;
  }
}
