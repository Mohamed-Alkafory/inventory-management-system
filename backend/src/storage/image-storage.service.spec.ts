import { BadRequestException, PayloadTooLargeException } from '@nestjs/common';
import {
  mkdir,
  mkdtemp,
  readFile,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import {
  MAX_AVATAR_SIZE_BYTES,
  MAX_IMAGE_SIZE_BYTES,
  ImageStorageService,
  type UploadedImageFile,
} from './image-storage.service.js';

const JPEG = Buffer.concat([
  Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46]),
  Buffer.alloc(32),
]);

// 1x1 transparent PNG.
const PNG = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=',
  'base64',
);

const WEBP = Buffer.concat([
  Buffer.from('RIFF', 'ascii'),
  Buffer.from([0x24, 0x00, 0x00, 0x00]),
  Buffer.from('WEBPVP8 ', 'ascii'),
  Buffer.alloc(32),
]);

const asFile = (buffer: Buffer, originalname = 'upload.bin'): UploadedImageFile => ({
  buffer,
  size: buffer.length,
  mimetype: 'application/octet-stream',
  originalname,
});

describe('ImageStorageService', () => {
  let directory: string;
  let service: ImageStorageService;

  beforeEach(async () => {
    directory = await mkdtemp(join(tmpdir(), 'inventory-images-'));
    service = new ImageStorageService({
      get: () => directory,
    } as never);
    await service.onModuleInit();
  });

  afterEach(async () => {
    await rm(directory, { recursive: true, force: true });
  });

  it.each([
    ['JPEG', JPEG, '.jpg'],
    ['PNG', PNG, '.png'],
    ['WebP', WEBP, '.webp'],
  ])(
    'saves a valid %s file into the requested folder using the detected extension',
    async (_name, buffer, extension) => {
      const imageUrl = await service.save(
        asFile(buffer, 'client-file.png'),
        'avatars',
      );

      expect(imageUrl.startsWith('/uploads/avatars/')).toBe(true);
      expect(imageUrl.endsWith(extension)).toBe(true);
      // The client filename is never used.
      expect(imageUrl).not.toContain('client-file');

      const filename = imageUrl.slice('/uploads/avatars/'.length);
      const written = await readFile(
        join(service.uploadsDir, 'avatars', filename),
      );
      expect(written.equals(buffer)).toBe(true);
    },
  );

  it('rejects a fake .png with non-image content', async () => {
    await expect(
      service.save(asFile(Buffer.from('not really a png'), 'fake.png'), 'avatars'),
    ).rejects.toBeInstanceOf(BadRequestException);
  });

  it('rejects an unsupported real image type (GIF)', async () => {
    const gif = Buffer.from('GIF89a', 'ascii');

    await expect(
      service.save(asFile(gif, 'animation.gif'), 'avatars'),
    ).rejects.toBeInstanceOf(BadRequestException);
  });

  it('rejects an avatar larger than 1 MB', async () => {
    const tooLarge = Buffer.alloc(MAX_AVATAR_SIZE_BYTES + 1);

    await expect(
      service.save(asFile(tooLarge), 'avatars', MAX_AVATAR_SIZE_BYTES),
    ).rejects.toBeInstanceOf(PayloadTooLargeException);
  });

  it('keeps the 2 MB default for product images', async () => {
    const tooLarge = Buffer.alloc(MAX_IMAGE_SIZE_BYTES + 1);

    await expect(
      service.save(asFile(tooLarge), 'products'),
    ).rejects.toBeInstanceOf(PayloadTooLargeException);
  });

  it('rejects an empty or missing file', async () => {
    await expect(service.save(undefined, 'avatars')).rejects.toBeInstanceOf(
      BadRequestException,
    );
    await expect(
      service.save(asFile(Buffer.alloc(0)), 'avatars'),
    ).rejects.toBeInstanceOf(BadRequestException);
  });

  it('rejects an unsafe folder name', async () => {
    await expect(
      service.save(asFile(PNG), '../outside'),
    ).rejects.toBeInstanceOf(BadRequestException);
  });

  it('deletes an existing local file', async () => {
    const imageUrl = await service.save(asFile(PNG), 'avatars');
    const filename = imageUrl.slice('/uploads/avatars/'.length);
    const absolutePath = join(service.uploadsDir, 'avatars', filename);

    await service.delete(imageUrl);

    await expect(stat(absolutePath)).rejects.toMatchObject({ code: 'ENOENT' });
  });

  it('ignores a missing file', async () => {
    await expect(
      service.delete('/uploads/avatars/00000000-0000-4000-8000-000000000000.png'),
    ).resolves.toBeUndefined();
  });

  it('never deletes external URLs', async () => {
    const external = 'https://example.com/image.png';
    expect(service.resolveLocalPath(external)).toBeNull();

    await expect(service.delete(external)).resolves.toBeUndefined();
  });

  it('never deletes files that were not generated by save()', async () => {
    const uploadedByHand = join(service.uploadsDir, 'avatars', 'hand-made.png');
    await mkdir(join(service.uploadsDir, 'avatars'), { recursive: true });
    await writeFile(uploadedByHand, PNG);

    await service.delete('/uploads/avatars/hand-made.png');

    await expect(stat(uploadedByHand)).resolves.toBeDefined();
  });

  it('refuses path traversal and nested paths', async () => {
    const outside = join(directory, 'secret.png');
    await writeFile(outside, PNG);

    for (const candidate of [
      '/uploads/avatars/../secret.png',
      '/uploads/avatars/..\\secret.png',
      '/uploads/avatars/nested/00000000-0000-4000-8000-000000000000.png',
      '/uploads/avatars/00000000-0000-4000-8000-000000000000.exe',
      'uploads/avatars/00000000-0000-4000-8000-000000000000.png',
    ]) {
      expect(service.resolveLocalPath(candidate)).toBeNull();
      await expect(service.delete(candidate)).resolves.toBeUndefined();
    }

    await expect(stat(outside)).resolves.toBeDefined();
  });
});
